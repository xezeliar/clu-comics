def appearance_slots(appearance):
    """[(theme_id, media query or None)]: the one theme, or both of Follow my
    device's with the scheme each applies to."""
    if appearance["mode"] == "follow":
        return [(appearance["light"], "(prefers-color-scheme: light)"),
                (appearance["dark"], "(prefers-color-scheme: dark)")]
    return [(appearance["theme"], None)]


def appearance_css(appearance):
    """The inline <style> for True black and the accent ("" when neither is
    on). Built only from validated values (normalize_appearance), so it is
    safe to emit unescaped."""
    out = []
    for theme_id, media in appearance_slots(appearance):
        pal = theme_palette(theme_id)
        page, css = pal["page"], ""
        if appearance["oled"] and is_dark_theme(theme_id):
            page, css = TRUE_BLACK["page"], _true_black_css()
        if appearance["accent"]:
            css += _accent_css(appearance["accent"], page, pal["emphasis"])
        if css:
            out.append(f"@media {media}{{{css}}}" if media else css)
    return "".join(out)
