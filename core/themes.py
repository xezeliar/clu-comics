THEME_MODES = ("one", "follow")
# What an appearance with nothing stored resolves to.
APPEARANCE_DEFAULTS = {
    "theme": "default", "mode": "one", "light": "default", "dark": "darkly",
    "oled": False, "accent": "",
}


def normalize_appearance(raw):
    """``raw`` (stored values, possibly stale or junk) as a valid appearance.

    The accent is written into an inline <style>, so it is only ever one of
    the swatches; anything else becomes the theme's own."""
    raw = raw or {}
    out = dict(APPEARANCE_DEFAULTS)
    if is_valid_theme(raw.get("theme")):
        out["theme"] = raw["theme"]
    if raw.get("mode") in THEME_MODES:
        out["mode"] = raw["mode"]
    if is_valid_theme(raw.get("light")) and not is_dark_theme(raw["light"]):
        out["light"] = raw["light"]
    if is_dark_theme(raw.get("dark")):
        out["dark"] = raw["dark"]
    out["oled"] = raw.get("oled") is True
    if raw.get("accent") in ACCENT_COLOURS:
        out["accent"] = raw["accent"]
    return out


def _rgb(hex_color):
    h = hex_color.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _luminance(hex_color):
    def channel(c):
        c /= 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (channel(c) for c in _rgb(hex_color))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    """WCAG 2 contrast ratio between two hex colours."""
    hi, lo = sorted((_luminance(a), _luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def toward(a, b, t):
    """``a`` moved a share ``t`` of the way to ``b``, in sRGB."""
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(_rgb(a), _rgb(b)))


def accent_text_side(fill, page, ink):
    """The text side of an accent (links, outline buttons, selection): the
    same hue stepped toward the page's ink until it reads 4.5:1 on the page."""
    for step in range(21):
        colour = toward(fill, ink, step / 20)
        if contrast(colour, page) >= 4.5:
            return colour
    return ink


def _rgb_list(hex_color):
    return ", ".join(str(c) for c in _rgb(hex_color))


def _svg_url(svg):
    encoded = (svg.replace("%", "%25").replace("#", "%23").replace("<", "%3c")
               .replace(">", "%3e").replace('"', "'"))
    return 'url("data:image/svg+xml,' + encoded + '")'


